import Foundation
var checks = 0
func check(_ condition: Bool) { checks += 1; precondition(condition) }
var decoder = EmbeddedCommandDecoder()
check(decoder.feed(Data("set".utf8)).isEmpty)
check(decoder.feed(Data("tings\npair\n".utf8)) == [.settings, .pair])
check(decoder.feed(Data("quit\nsettings\n".utf8)) == [.quit])
check(decoder.closed)
check(decoder.feed(Data("pair\n".utf8)).isEmpty)
var malformed = EmbeddedCommandDecoder()
check(malformed.feed(Data("execute something\n".utf8)) == [.quit])
var oversized = EmbeddedCommandDecoder()
check(oversized.feed(Data(repeating: 65, count: 100_000)) == [.quit])
var invalidUTF8 = EmbeddedCommandDecoder()
check(invalidUTF8.feed(Data([255, 10])) == [.quit])
var crlf = EmbeddedCommandDecoder()
check(crlf.feed(Data("pair\r\n".utf8)) == [.quit])
var empty = EmbeddedCommandDecoder()
check(empty.feed(Data([10])) == [.quit])
let standalone = KeychainItemNames()
check(standalone.service == "me.saffer.sill.remote")
check(standalone.keyTag == Data("me.saffer.sill.remote.host-key".utf8))
let embedded = KeychainItemNames(namespace: "com.example.app.streaming-host")
check(embedded != standalone)
check(embedded.service == "com.example.app.streaming-host.sill.remote")
check(embedded.keyTag == Data("com.example.app.streaming-host.sill.remote.host-key".utf8))
check(KeychainItemNames(namespace: "com.example.app.dev.streaming-host") != embedded)
print("embedded-control: \(checks) checks passed")
