def struct_fields(name, struct):
    sm = find(name, r"^struct " + struct + r" \{\n(.*?)^    static let", re.S)
    fields = re.findall(r"^    let (\w+): (CGFloat|Double|Bool)", sm.group(1), re.M)
    return fields


def kt_type(t):
    return {"CGFloat": "Double", "Double": "Double", "Bool": "Boolean"}[t]


def instances(name, struct, kotlin_struct, which, fields):
    out = []
    for inst in which:
        im = find(name, r"static let " + inst + r" = " + struct + r"\((.*?)\)\n", re.S)
        args = {}
        for am in re.finditer(r"(\w+):\s*((?:[^,()]|\([^()]*\))+)", im.group(1)):
            args[am.group(1)] = am.group(2).strip()
        missing = [f for f, _ in fields if f not in args]
        if missing:
            sys.exit(f"extract_tokens: {struct}.{inst} lacks {missing}")
        parts = []
        for f, t in fields:
            v = args[f]
            if t == "Bool":
                parts.append(f"{f} = {v}")
            elif num(v) is not None:
                parts.append(f"{f} = {kt_double(v)}")
            else:
                # An expression of PhonePortraitLayout's constants: Kotlin reads it as Swift does.
                if not re.fullmatch(r"[\w.\s()+\-*/0-9]+", v):
                    sys.exit(f"extract_tokens: {struct}.{inst}.{f} = {v!r} is not an expression this reads")
                parts.append(f"{f} = ({v}).toDouble()")
        where = line_of(name, im.start())
        out.append(f"        /** {name} */")
        out.append(f"        val {inst} = {kotlin_struct}(" + ", ".join(parts) + ")")
    return out


