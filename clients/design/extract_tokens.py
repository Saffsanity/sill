#!/usr/bin/env python3
"""Sill's design tokens for the clients that are not Swift, read from the iPhone and iPad app.

The iOS app is the design's source of truth: its colours are `Palette` (StreamScreen.swift), its
bars' numbers `BarMetrics` and `PortraitMetrics`, and everything else a literal at the one place
that draws it. This reads each of them from the Swift source, at an anchor that must match, and
writes clients/core/src/main/kotlin/me/saffer/sill/core/ui/Tokens.kt, which the Android app, the
Windows client and the Windows and Linux hosts draw with. Nothing is typed twice: a change on the
iOS side changes the generated file, and `generate.sh --verify` (clients.yml) fails until the
regenerated file is committed. An anchor that no longer matches stops the run, naming it.

    extract_tokens.py IOS_DIR OUT_KT
"""
import os
import re
import sys

ios, out = sys.argv[1], sys.argv[2]
sources = {}


def src(name):
    if name not in sources:
        with open(os.path.join(ios, name), encoding="utf-8") as f:
            sources[name] = f.read()
    return sources[name]


def line_of(name, pos):
    return src(name).count("\n", 0, pos) + 1


def find(name, pattern, flags=0):
    m = re.search(pattern, src(name), flags | re.M)
    if not m:
        sys.exit(f"extract_tokens: no match in {name} for {pattern!r}: the iOS source changed; update the anchor")
    return m


def num(s):
    s = s.strip()
    return float(s) if re.fullmatch(r"-?\d+(\.\d+)?", s) else None


def kt_double(v):
    return repr(float(v))


