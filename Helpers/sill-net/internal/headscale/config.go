package headscale

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

// ConfigParams are the paths and ports Headscale's generated config needs.
type ConfigParams struct {
	StateDir string // holds keys, db, socket, policy
	Port     int    // loopback listen port (also the server_url port)
}

// SocketPath is where Headscale's CLI socket lives.
//
// A unix socket path is limited to 104 bytes on macOS (sun_path), and
// Headscale fails with a bare "bind: invalid argument" past it. Inside the
// state dir is preferred (private, cleaned up with the data); a long home
// directory or test dir falls back to a short per-user path under /tmp,
// protected by a 0700 directory.
func SocketPath(stateDir string) string {
	p := filepath.Join(stateDir, "headscale.sock")
	if len(p) < 100 {
		return p
	}
	dir := filepath.Join(os.TempDir(), fmt.Sprintf("sill-net-%d", os.Getuid()))
	if len(dir) > 60 {
		dir = fmt.Sprintf("/tmp/sill-net-%d", os.Getuid())
	}
	_ = os.MkdirAll(dir, 0o700)
	_ = os.Chmod(dir, 0o700)
	return filepath.Join(dir, "headscale.sock")
}

// Tags. Every device Sill invites joins as DeviceTag; the Mac's own node is
// MacTag. The policy lets a device reach the Mac's one port and nothing else:
// not another device, not any other port on the Mac.
const (
	MacTag    = "tag:sill-mac"
	DeviceTag = "tag:sill-device"
	// DoorPort is the port the Mac's tailnet node listens on, forwarded to
	// Sill's relay door on loopback.
	DoorPort = 7455
)

// Policy is the whole ACL policy, static: who may reach whom never depends on
// runtime state, so it is a file Headscale reads once, not something edited
// through the API.
//
// The owner is a user that never exists. Headscale 0.29 checks tagOwners only
// when a node asks for a tag itself; a preauth key minted through the API
// with the tag already on it is accepted as is, which is the only way Sill
// hands out tags (sill-net holds the one API key).
func Policy() string {
	return fmt.Sprintf(`// Generated by sill-net on every start; edit sill-net, not this file.
{
  "groups": {
    "group:sill": ["sill@getsill.app"],
  },
  "tagOwners": {
    %[1]q: ["group:sill"],
    %[2]q: ["group:sill"],
  },
  "acls": [
    // An invited device reaches the Mac's door, and nothing else.
    {"action": "accept", "src": [%[2]q], "dst": ["%[1]s:%[3]d"]},
  ],
  // No SSH: a device must never get a shell on the Mac this way.
  "ssh": [],
}
`, MacTag, DeviceTag, DoorPort)
}

// WriteConfig writes Headscale's config.yaml and policy into StateDir,
// byte-compared so an unchanged regeneration does not touch the files.
//
// server_url is loopback on purpose. Remote devices never use it directly:
// they reach Headscale through the relay at https://<fingerprint>.<relay>,
// via a control shim that pins the Noise key, so the URL Headscale believes
// it lives at only matters to the local tsnet node and the CLI.
func WriteConfig(p ConfigParams) (string, error) {
	if err := os.MkdirAll(p.StateDir, 0o700); err != nil {
		return "", err
	}
	policyPath := filepath.Join(p.StateDir, "policy.hujson")
	if err := writeIfChanged(policyPath, []byte(Policy())); err != nil {
		return "", err
	}
	path := filepath.Join(p.StateDir, "config.yaml")
	body := fmt.Sprintf(`# Generated by sill-net -- regenerated on every start; edit sill-net, not this file.
server_url: http://127.0.0.1:%[1]d
listen_addr: 127.0.0.1:%[1]d
# Headscale insists on binding these even though nothing here uses them.
metrics_listen_addr: 127.0.0.1:0
grpc_listen_addr: 127.0.0.1:0
grpc_allow_insecure: false

noise:
  private_key_path: %[2]s/noise_private.key

# Narrow and distinctive so these addresses are recognisable in logs. Overlap
# with a real Tailscale tailnet on the same Mac is harmless: sill-net's node
# is userspace (tsnet), with no TUN device and no system route, and the device
# reaches it through a loopback forward inside Sill.
prefixes:
  v4: 100.91.0.0/16
  v6: fd7a:115c:a1e0:9100::/64
  allocation: sequential

# Default is /var/run/headscale, which an unprivileged app cannot create.
unix_socket: %[3]s
unix_socket_permission: "0700"

database:
  type: sqlite
  sqlite:
    path: %[2]s/db.sqlite

# Headscale refuses to start when base_domain equals the server_url domain.
dns:
  magic_dns: true
  base_domain: sill.internal
  override_local_dns: false
  nameservers:
    global: []

policy:
  mode: file
  path: %[4]s

# Headscale refuses an empty DERP map. Tailscale's public DERP servers relay
# WireGuard packets (end-to-end encrypted) when a device and the Mac cannot
# connect directly, e.g. both behind symmetric NAT. Inside them, Sill's own
# TLS with pinned keys: DERP sees ciphertext twice over.
derp:
  urls:
    - https://controlplane.tailscale.com/derpmap/default
  auto_update_enabled: false

log:
  level: info

logtail:
  enabled: false
`, p.Port, p.StateDir, SocketPath(p.StateDir), policyPath)
	return path, writeIfChanged(path, []byte(body))
}

func writeIfChanged(path string, body []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, body) {
		return nil
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, body, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
